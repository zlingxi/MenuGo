//! Tiny INI-style settings store, matching the portable nature of the original
//! tool. Drop a `portable.flag` file next to the executable to keep settings
//! beside the binary instead of in %APPDATA%\MenuGo.

use crate::models::Settings;
use std::fs;
use std::io;
use std::path::PathBuf;

const FILE_NAME: &str = "settings.ini";

pub fn config_path() -> PathBuf {
    if let Ok(exe) = std::env::current_exe() {
        if let Some(dir) = exe.parent() {
            if dir.join("portable.flag").exists() {
                return dir.join(FILE_NAME);
            }
        }
    }
    let base = std::env::var_os("APPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."));
    base.join("MenuGo").join(FILE_NAME)
}

pub fn load() -> Settings {
    let Ok(text) = fs::read_to_string(config_path()) else {
        return Settings::default();
    };
    let mut settings = Settings::default();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty()
            || line.starts_with(';')
            || line.starts_with('#')
            || line.starts_with('[')
        {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let value = value.trim();
        match key.trim().to_ascii_lowercase().as_str() {
            "language" => settings.language = value.to_string(),
            "theme" => settings.theme = normalize_theme(value),
            "applytoallusers" => settings.apply_to_all_users = parse_bool(value),
            "autorestartexplorer" => settings.auto_restart_explorer = parse_bool(value),
            _ => {}
        }
    }
    settings
}

pub fn save(settings: &Settings) -> io::Result<()> {
    let path = config_path();
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let text = format!(
        "; Generated by MenuGo\n[Main]\nLanguage={}\nTheme={}\nApplyToAllUsers={}\nAutoRestartExplorer={}\n",
        settings.language,
        settings.theme,
        u8::from(settings.apply_to_all_users),
        u8::from(settings.auto_restart_explorer),
    );
    fs::write(path, text)
}

fn parse_bool(value: &str) -> bool {
    matches!(
        value.to_ascii_lowercase().as_str(),
        "1" | "true" | "yes" | "on"
    )
}

fn normalize_theme(value: &str) -> String {
    let value = value.trim().to_ascii_lowercase();
    match value.as_str() {
        "dark" | "system" => value,
        _ => "light".into(),
    }
}
